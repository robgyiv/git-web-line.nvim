local assert = require('luassert')
local helpers = require('test.helpers')

describe(':GitWebLine', function()
  local captured, root

  before_each(function()
    captured = helpers.capture()
    root = helpers.create_repo()
    helpers.git({ 'remote', 'add', 'upstream', 'https://gitlab.com/org/repo.git' }, root)
    helpers.push(root)
    helpers.push(root, { remote = 'upstream' })
    vim.cmd.edit(root .. '/file.txt')
  end)

  after_each(function()
    captured.restore()
    vim.cmd('silent! %bwipeout!')
  end)

  it('should open the URL for the default remote', function()
    vim.cmd('GitWebLine')
    assert.same({}, captured.errors)
    assert.same({ 'https://github.com/user/repo/blob/main/file.txt#L1' }, captured.urls)
  end)

  it('should pass the remote argument through', function()
    vim.cmd('GitWebLine upstream')
    assert.same({}, captured.errors)
    assert.same({ 'https://gitlab.com/org/repo/-/blob/main/file.txt#L1' }, captured.urls)
  end)

  it('should link to the cursor line without a range', function()
    vim.api.nvim_buf_set_lines(0, 0, -1, false, { 'a', 'b', 'c' })
    vim.cmd('silent write')
    helpers.git({ 'commit', '-q', '-am', 'lines' }, root)
    helpers.push(root)
    vim.api.nvim_win_set_cursor(0, { 3, 0 })
    vim.cmd('GitWebLine')
    assert.same({ 'https://github.com/user/repo/blob/main/file.txt#L3' }, captured.urls)
  end)

  it('should link to a range', function()
    vim.api.nvim_buf_set_lines(0, 0, -1, false, { 'a', 'b', 'c', 'd' })
    vim.cmd('silent write')
    helpers.git({ 'commit', '-q', '-am', 'lines' }, root)
    helpers.push(root)
    vim.cmd('2,4GitWebLine upstream')
    assert.same({}, captured.errors)
    assert.same({ 'https://gitlab.com/org/repo/-/blob/main/file.txt#L2-4' }, captured.urls)
  end)

  it('should link to a visual selection', function()
    vim.api.nvim_buf_set_lines(0, 0, -1, false, { 'a', 'b', 'c', 'd' })
    vim.cmd('silent write')
    helpers.git({ 'commit', '-q', '-am', 'lines' }, root)
    helpers.push(root)
    vim.api.nvim_win_set_cursor(0, { 2, 0 })
    vim.cmd('normal! Vj')
    vim.cmd('execute "normal! \\<Esc>"')
    vim.cmd("'<,'>GitWebLine")
    assert.same({ 'https://github.com/user/repo/blob/main/file.txt#L2-L3' }, captured.urls)
  end)

  it('should copy instead of opening with a bang', function()
    vim.cmd('GitWebLine!')
    assert.same({}, captured.urls)
    assert.equals('https://github.com/user/repo/blob/main/file.txt#L1', captured.registers['+'])
  end)

  it('should copy a range for a remote with a bang', function()
    vim.cmd('1,1GitWebLine! upstream')
    assert.equals('https://gitlab.com/org/repo/-/blob/main/file.txt#L1', captured.registers['+'])
  end)

  it('should complete remote names on the command line', function()
    assert.same({ 'upstream' }, vim.fn.getcompletion('GitWebLine up', 'cmdline'))
  end)

  it('should treat extra words as an unknown remote', function()
    vim.cmd('GitWebLine origin upstream')
    assert.same({}, captured.urls)
    assert.truthy(captured.errors[1]:match("'origin upstream' does not exist"))
  end)
end)
