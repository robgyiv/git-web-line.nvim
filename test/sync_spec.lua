local assert = require('luassert')
local git_web_line = require('git-web-line')
local config = require('git-web-line.config')
local helpers = require('test.helpers')

describe('unpushed changes', function()
  local captured, root

  before_each(function()
    captured = helpers.capture()
    root = helpers.create_repo({ files = { ['file.lua'] = 'one\ntwo' } })
  end)

  after_each(function()
    captured.restore()
    config.setup()
    vim.cmd('silent! %bwipeout!')
  end)

  local function activate(mode)
    config.setup({ on_unpushed = mode })
    vim.cmd.edit(root .. '/file.lua')
    git_web_line.activate()
  end

  it('should open the branch URL without warnings when everything is pushed', function()
    helpers.push(root)
    activate('abort')
    assert.same({}, captured.errors)
    assert.same({}, captured.warnings)
    assert.same({ 'https://github.com/user/repo/blob/main/file.lua#L1' }, captured.urls)
  end)

  it('should use the upstream branch name for the remote ref', function()
    helpers.git({ 'checkout', '-q', '-b', 'local-name' }, root)
    helpers.push(root, { branch = 'remote-name', upstream = 'local-name' })
    activate('abort')
    assert.same({}, captured.errors)
    assert.equals(1, #captured.urls)
  end)

  describe('warn', function()
    it('should warn and open the branch URL when the branch is not pushed', function()
      activate('warn')
      assert.truthy(captured.warnings[1]:match("branch 'main' has not been pushed"))
      assert.same({ 'https://github.com/user/repo/blob/main/file.lua#L1' }, captured.urls)
    end)
  end)

  describe('abort', function()
    it('should abort when the branch is not pushed', function()
      activate('abort')
      assert.same({}, captured.urls)
      assert.truthy(captured.errors[1]:match('has not been pushed'))
    end)

    it('should abort when commits are ahead of the remote', function()
      helpers.push(root)
      helpers.commit(root, 'file.lua', 'one\ntwo\nthree')
      activate('abort')
      assert.same({}, captured.urls)
      assert.truthy(captured.errors[1]:match('1 commit%(s%) not pushed'))
    end)

    it('should abort when the file has uncommitted changes', function()
      helpers.push(root)
      vim.fn.writefile({ 'changed' }, root .. '/file.lua')
      activate('abort')
      assert.same({}, captured.urls)
      assert.truthy(captured.errors[1]:match('uncommitted changes'))
    end)

    it('should abort when the buffer has unsaved changes', function()
      helpers.push(root)
      config.setup({ on_unpushed = 'abort' })
      vim.cmd.edit(root .. '/file.lua')
      vim.api.nvim_buf_set_lines(0, 0, 0, false, { 'new line' })
      git_web_line.activate()
      assert.same({}, captured.urls)
      assert.truthy(captured.errors[1]:match('uncommitted changes'))
    end)

    it('should ignore uncommitted changes in other files', function()
      helpers.push(root)
      vim.fn.writefile({ 'other' }, root .. '/README.md')
      activate('abort')
      assert.same({}, captured.errors)
      assert.equals(1, #captured.urls)
    end)

    it('should abort on a detached HEAD that is not pushed', function()
      helpers.git({ 'checkout', '-q', '--detach' }, root)
      activate('abort')
      assert.same({}, captured.urls)
      assert.truthy(captured.errors[1]:match('commit has not been pushed'))
    end)

    it('should accept a detached HEAD contained in a remote branch', function()
      helpers.push(root)
      helpers.git({ 'checkout', '-q', '--detach' }, root)
      activate('abort')
      assert.same({}, captured.errors)
      assert.equals(1, #captured.urls)
    end)
  end)

  describe('permalink', function()
    it('should link to the newest pushed commit when ahead of the remote', function()
      local pushed = helpers.git({ 'rev-parse', 'HEAD' }, root)
      helpers.push(root)
      helpers.commit(root, 'file.lua', 'one\ntwo\nthree')
      activate('permalink')
      assert.same(
        { 'https://github.com/user/repo/blob/' .. pushed .. '/file.lua#L1' },
        captured.urls
      )
      assert.truthy(captured.warnings[1]:match('linking to pushed commit ' .. pushed:sub(1, 7)))
    end)

    it('should link to the merge base when the remote has diverged', function()
      local base = helpers.git({ 'rev-parse', 'HEAD' }, root)
      helpers.git({ 'checkout', '-q', '-b', 'other' }, root)
      helpers.commit(root, 'file.lua', 'remote change')
      helpers.push(root, { sha = 'HEAD' })
      helpers.git({ 'checkout', '-q', 'main' }, root)
      helpers.commit(root, 'file.lua', 'local change')
      activate('permalink')
      assert.same({ 'https://github.com/user/repo/blob/' .. base .. '/file.lua#L1' }, captured.urls)
    end)

    it('should abort when nothing has been pushed', function()
      activate('permalink')
      assert.same({}, captured.urls)
      assert.truthy(captured.errors[1]:match('no pushed commit'))
    end)
  end)

  it('should reject an invalid on_unpushed value', function()
    assert.has_error(function()
      config.setup({ on_unpushed = 'nope' })
    end)
  end)
end)
